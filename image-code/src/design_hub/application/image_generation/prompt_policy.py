GLOBAL_IMAGE_QUALITY_POLICY = """本约束只用于提高画面的真实性、文字准确度与细节完成度，不得改变本次任务明确指定的主体、数量、构图、画幅比例、颜色、场景、文案、参考图角色和艺术风格。

严格遵循本次任务对参考图角色的定义。被指定为产品图、主体图或编辑源图的内容，应保持其外形、结构、比例、材质、颜色、图案、包装、已有文字与 Logo 一致，除非用户明确要求修改。被指定为风格、构图或场景参考的图片，只学习任务明确要求的视觉特征，不得擅自复制其中的产品、人物、文字、Logo 或品牌元素。

对于照片、商品图和其他物理场景，主体结构、比例、透视、连接关系和边缘必须自然准确；产品、人物、动物及其他物体不得出现融合、重复、残缺、悬浮、错位、异常肢体或不合理变形。材质应符合真实物理特征，保留合理纹理、表面层次和细微自然差异，避免塑料感、蜡感、过度磨皮、过度锐化、虚假反光、整面高光和 AI 涂抹痕迹。

对于存在真实光照的画面，光源方向必须统一，曝光自然，高光不过曝，暗部保留细节。只保留真实接触阴影和符合主光源方向的自然投影；禁止多重阴影、无来源阴影、悬浮阴影、重复影子、过重黑边和不自然的棚拍假阴影。对于 Logo、扁平插画、图标、纯平面设计或透明底素材，不得擅自添加写实光影、立体效果或投影。

只有本次任务指定需要保留的已有文字，或用户明确要求生成的文案，才允许出现在画面中。指定文字必须一字不增、一字不减、一字不改，清晰可读，字形完整，间距与排版自然；禁止错字、乱码、重复文字、变形文字和伪文字。未经明确要求，不得新增营销词、标签、Logo、水印、装饰字符或其他文字。

用户未指定非写实风格时，物理场景默认呈现自然可信的真实质感。用户明确指定插画、卡通、3D、油画、平面设计等风格时，只提升该风格内部的结构、材质、文字和光影可信度，不强制改成照片，不额外改变其视觉语言。

主体与背景的清晰度、色温、颗粒、景深和光照关系应保持协调；边缘融合自然，避免抠图白边、异常光晕、锯齿、穿帮、拼接痕迹、局部分辨率不一致和局部风格突变。上述要求仅在对应画面类型适用时执行，不得为了套用质量规则而添加用户没有要求的内容。"""


def compose_image_api_prompt(task_prompt: str, negative_prompt: str) -> str:
    task = task_prompt.strip()
    if not task:
        raise ValueError("task prompt must not be empty")

    sections = [
        f"【全局真实性与细节质量约束】\n\n{GLOBAL_IMAGE_QUALITY_POLICY}",
        f"【本次生图要求】\n\n{task}",
    ]
    negative = negative_prompt.strip()
    if negative:
        sections.append(f"【需要避免】\n\n{negative}")
    return "\n\n".join(sections)
